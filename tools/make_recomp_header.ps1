# Regenerates recomp/runtime/recomp.h from N64Recomp's header, swapping in our memory section.
$src = Get-Content D:\Buriki\third_party\N64Recomp\include\recomp.h -Raw
$start = $src.IndexOf('#define MEM_W(offset, reg)')
$end = $src.IndexOf('static inline uint32_t get_cop1_cs()')
if ($start -lt 0 -or $end -lt 0) { throw "N64Recomp's recomp.h changed shape; update make_recomp_header.ps1" }
$mid = Get-Content -Raw D:\Buriki\recomp\runtime\recomp_mem_section.txt
$hdr = "// Buriki One copy of N64Recomp's include/recomp.h (MIT licence, (c) N64Recomp contributors).`r`n// Generated by tools/make_recomp_header.ps1: the memory macros are replaced by the`r`n// section in runtime/recomp_mem_section.txt. Edit that file, not this one.`r`n"
$out = $hdr + $src.Substring(0, $start) + $mid + $src.Substring($end)
# In C++, "extern inline" functions are only emitted where they're used, so functions only
# reached through the function table would vanish. Drop "extern inline" (keep weak/noinline).
$old = '#define RECOMP_FUNC extern inline __attribute__((weak,noinline))'
if (-not $out.Contains($old)) { throw "RECOMP_FUNC definition not found; update make_recomp_header.ps1" }
$out = $out.Replace($old, '#define RECOMP_FUNC __attribute__((weak,noinline))')
# NAN_CHECK asserts on NaN float operands. The real VR4300 just propagates quiet NaNs, so
# log the first few occurrences (runtime/hw.cpp) and keep running instead of aborting.
$oldNan = "#define NAN_CHECK(val) \`n    assert(val == val)"
$out = $out.Replace("`r`n", "`n")
if (-not $out.Contains($oldNan)) { throw "NAN_CHECK definition not found; update make_recomp_header.ps1" }
$out = $out.Replace($oldNan, "extern `"C`" void hw_note_nan(const char* func, void* ctx);`n#define NAN_CHECK(val) \`n    do { if ((val) != (val)) hw_note_nan(__func__, ctx); } while (0)")
[IO.File]::WriteAllText('D:\Buriki\recomp\runtime\recomp.h', $out)
