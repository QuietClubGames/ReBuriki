"""Write recomp/runtime/func_table.cpp: every function start address -> recompiled function.

The runtime uses it for function-pointer calls (jalr). Includes the hand-written kernel
functions, which N64Recomp skips but the runtime provides.

Usage: make_func_table.py <syms.toml> <out.cpp>
"""
import re, sys
syms, out_path = sys.argv[1:3]
names = sorted(set(re.findall(r'name = "(func_[0-9A-F]{8})"', open(syms).read())),
               key=lambda n: int(n[5:], 16))
with open(out_path, 'w') as f:
    f.write('// Generated by tools/make_func_table.py. Do not edit.\n')
    f.write('#include "recomp.h"\n#include "kernel.h"\n#include "funcs.h"\n\n')
    f.write('struct FuncTableEntry { uint32_t vram; recomp_func_t* func; };\n')
    f.write('extern "C" const FuncTableEntry g_func_table[] = {\n')
    for n in names:
        f.write('    { 0x%s, %s },\n' % (n[5:], n))
    f.write('};\nextern "C" const size_t g_func_table_size = %d;\n' % len(names))
print('function table:', len(names))
