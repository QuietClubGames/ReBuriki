"""Make recomp/runtime/recomp.h from N64Recomp's include/recomp.h, swapping in our memory section.

Usage: make_recomp_header.py <N64Recomp recomp.h> <recomp_mem_section.txt> <out recomp.h>
"""
import sys

src_path, mid_path, out_path = sys.argv[1:4]
src = open(src_path, encoding='utf-8').read().replace('\r\n', '\n')
mid = open(mid_path, encoding='utf-8').read().replace('\r\n', '\n')
BS = chr(92)   # a backslash (line continuation in the C macros below)

start = src.find('#define MEM_W(offset, reg)')
end = src.find('static inline uint32_t get_cop1_cs()')
if start < 0 or end < 0:
    sys.exit("N64Recomp's recomp.h changed shape; update make_recomp_header.py")
hdr = ("// Buriki One copy of N64Recomp's include/recomp.h (MIT licence, (c) N64Recomp contributors).\n"
       "// Generated by tools/make_recomp_header.py: the memory macros are replaced by the\n"
       "// section in runtime/recomp_mem_section.txt. Edit that file, not this one.\n")
out = hdr + src[:start] + mid + src[end:]

# In C++, "extern inline" functions are only emitted where they're used, so functions only
# reached through the function table would vanish. Drop "extern inline" (keep weak/noinline).
old = '#define RECOMP_FUNC extern inline __attribute__((weak,noinline))'
if old not in out:
    sys.exit('RECOMP_FUNC definition not found; update make_recomp_header.py')
out = out.replace(old, '#define RECOMP_FUNC __attribute__((weak,noinline))')

# NAN_CHECK asserts on NaN float operands. The real VR4300 just propagates quiet NaNs, so
# log the first few occurrences (runtime/hw.cpp) and keep running instead of aborting.
old = '#define NAN_CHECK(val) ' + BS + '\n    assert(val == val)'
if old not in out:
    sys.exit('NAN_CHECK definition not found; update make_recomp_header.py')
out = out.replace(old, 'extern "C" void hw_note_nan(const char* func, void* ctx);\n'
                       '#define NAN_CHECK(val) ' + BS + '\n'
                       '    do { if ((val) != (val)) hw_note_nan(__func__, ctx); } while (0)')
open(out_path, 'w', encoding='utf-8', newline='\n').write(out)
